def notes_url(name: str, watch_url: str, cfg: dict) -> str:
    """Release-notes page for a watch: config override, else derived from the
    watch URL (GitHub API -> the repo's releases page, Homebrew cask API -> the
    cask page), else the watched URL itself."""
    override = cfg.get("notes", {}).get(name)
    if override:
        return str(override)
    m = re.match(r"https://api\.github\.com/repos/([^/]+/[^/]+)/", watch_url)
    if m:
        return f"https://github.com/{m.group(1)}/releases"
    m = re.match(r"https://formulae\.brew\.sh/api/cask/([^.]+)\.json", watch_url)
    if m:
        return f"https://formulae.brew.sh/cask/{m.group(1)}"
    return watch_url


def get_api_key(cfg: dict) -> str:
    env_key = os.environ.get("SOFTWARE_VERSIONS_API_KEY", "").strip()
    if env_key:
        debug("api key from environment")
        return env_key
    try:
        result = subprocess.run(
            [
                "security",
                "find-generic-password",
                "-s",
                cfg["keychain_service"],
                "-a",
                cfg["keychain_account"],
                "-w",
            ],
            capture_output=True,
            text=True,
            timeout=REQUEST_TIMEOUT,
        )
        key = result.stdout.strip()
        if result.returncode == 0 and key:
            debug("api key from keychain")
            return key
    except (subprocess.TimeoutExpired, OSError):
        pass
    print_setup(
        "API key not found in Keychain",
        [
            "Add it once (key from changedetection.io Settings > API):",
            "  security add-generic-password -U \\",
            f"    -s {cfg['keychain_service']} -a {cfg['keychain_account']} -w '<key>'",
            "Then click Refresh and allow `security` access if asked.",
        ],
    )
    return ""  # unreachable


# ─── changedetection.io API ──────────────────────────────────────────────


class AuthError(Exception):
    pass


class Client:
    def __init__(self, base_url: str, api_key: str):
        self.base_url = base_url
        self.api_key = api_key

    def request(self, method: str, path: str, body: dict | None = None):
        """Return (status, text). Raises URLError on network failure."""
        data = json.dumps(body).encode() if body is not None else None
        req = urllib.request.Request(
            self.base_url + path, data=data, method=method
        )
        req.add_header("x-api-key", self.api_key)
        req.add_header("Accept", "application/json, text/plain")
        if data is not None:
            req.add_header("Content-Type", "application/json")
        try:
            with urllib.request.urlopen(req, timeout=REQUEST_TIMEOUT) as resp:
                return resp.status, resp.read().decode("utf-8", "replace")
        except urllib.error.HTTPError as exc:
            text = exc.read().decode("utf-8", "replace") if exc.fp else ""
            if exc.code in (401, 403):
                raise AuthError(text.strip() or f"HTTP {exc.code}") from exc
            return exc.code, text

    def list_watches(self, tag: str) -> dict:
        status, text = self.request(
            "GET", f"/api/v1/watch?tag={urllib.parse.quote(tag)}"
        )
        if status != 200:
            raise RuntimeError(f"watch list HTTP {status}")
        return json.loads(text)

    def latest_snapshot(self, uuid: str) -> str | None:
        status, text = self.request("GET", f"/api/v1/watch/{uuid}/history/latest")
        if status == 200:
            return text
        return None

    def first_seen(self, uuid: str) -> int:
        """Timestamp of the oldest stored snapshot (0 if none)."""
        status, text = self.request("GET", f"/api/v1/watch/{uuid}/history")
        if status != 200:
            return 0
        try:
            keys = [int(k) for k in json.loads(text).keys()]
            return min(keys) if keys else 0
        except (ValueError, AttributeError):
            return 0

    def set_title(self, uuid: str, title: str) -> bool:
        status, _ = self.request("PUT", f"/api/v1/watch/{uuid}", {"title": title})
        return status == 200

    def list_tags(self) -> dict:
        status, text = self.request("GET", "/api/v1/tags")
        if status != 200:
            raise RuntimeError(f"tag list HTTP {status}")
        return json.loads(text)

    def get_tag(self, uuid: str) -> dict:
        """Full tag record (the list endpoint omits notification fields)."""
        status, text = self.request("GET", f"/api/v1/tag/{uuid}")
        if status != 200:
            raise RuntimeError(f"tag HTTP {status}")
        return json.loads(text)

    def update_tag(self, uuid: str, fields: dict) -> bool:
        status, _ = self.request("PUT", f"/api/v1/tag/{uuid}", fields)
        return status == 200


# ─── Alert template ──────────────────────────────────────────────────────
# changedetection.io renders notification title/body as Jinja, and a tag's
# templates win over the global ones. The plugin keeps the tag's templates in
# sync so software alerts read "<name>: <new>" / "<old> → <new>" and link to
# the same release-notes page as the menu.

# First version-looking line of a snapshot, falling back to the first
# non-bracket line (JSON list filters start with "["). The version test exists
# because some release feeds lead with a rolling tag rather than a version:
# Karabiner-Elements' releases list starts with a literal "beta" and ghostty's
# with "tip", which made alerts read "Karabiner-Elements: beta" / "v16.3.0 →
# beta" when a new beta was published. The fallback keeps watches with no
# version at all (price pages, ghostty) behaving as they did before.
#
# The test is a regex_replace that blanks a whole version-looking token, so an
# empty result means "this line is a version". Two constraints on the pattern:
# changedetection rejects nested quantifiers such as (\.[0-9]+)+ as a ReDoS
# risk and then returns the value UNCHANGED, which would silently fail every
# line; and [.] avoids asking how backslashes survive a Jinja string literal.
# Requiring digit-dot-digit matches VERSION_RE's own floor.
_FIRST_LINE_MACRO = (
    "{% macro first(s) %}{% set ns = namespace(v='', f='') %}"
    "{% for l in (s or '').splitlines() %}{% set t = l | trim(' \",[]{}') %}"
    "{% if t %}{% if not ns.f %}{% set ns.f = t %}{% endif %}"
    "{% if not ns.v and (t | regex_replace('^[vV]?[0-9]+[.][0-9].*$', '')) == '' %}"
    "{% set ns.v = t %}{% endif %}{% endif %}{% endfor %}{{ ns.v or ns.f }}{% endmacro %}"
    "{% set name = watch_title.split(' · ')[0] %}{% set new = first(current_snapshot) %}"
)
ALERT_TITLE = _FIRST_LINE_MACRO + "{{ name }}: {{ new or 'changed' }}"
# A link ending in "/tag/" gets the new version appended (GitHub release page).
ALERT_BODY = (
    _FIRST_LINE_MACRO
    + "{% set links = __LINKS__ %}{% set link = links.get(name) or diff_url %}"
    "{% if link.endswith('/tag/') %}{% set link = link ~ new %}{% endif %}"
    "{{ first(prev_snapshot) or '?' }} → {{ new }}\n{{ link }}"
)


def alert_links(items: list[dict], cfg: dict) -> dict[str, str]:
    """Watch name -> release page for alerts. GitHub repos without a notes
    override link to the specific release; raw feeds (appcast XML, JSON) are
    left out so the alert falls back to the diff page."""
    links = {}
    for i in items:
        link = i.get("notes") or ""
        if i["name"] not in cfg["notes"] and re.fullmatch(r"https://github\.com/[^/]+/[^/]+/releases", link):
            link += "/tag/"
        elif re.search(r"\.(xml|json)(\?|$)", link):
            continue
        links[i["name"]] = link
    return links


def sync_alert_template(client: Client, items: list[dict], cfg: dict) -> str | None:
    """Write the tag's notification templates if they differ. Returns a warning."""
    title = ALERT_TITLE
    body = ALERT_BODY.replace("__LINKS__", json.dumps(alert_links(items, cfg), ensure_ascii=False, sort_keys=True))
    tag_uuid = next((u for u, t in client.list_tags().items() if t.get("title") == cfg["tag"]), None)
    if tag_uuid is None:
        return f"Tag {cfg['tag']!r} not found; alert template not synced"
    tag = client.get_tag(tag_uuid)
    if tag.get("notification_title") == title and tag.get("notification_body") == body:
        return None
    if not client.update_tag(tag_uuid, {"notification_title": title, "notification_body": body}):
        return "Could not update the alert template"
    debug("alert template updated")
    return None


# ─── Version handling ────────────────────────────────────────────────────


def parse_version(text: str) -> tuple[str | None, str]:
    """Return (version, first_line). version is None if nothing matched."""
    first_line = ""
    for line in text.splitlines():
        line = line.strip()
        if not line or line in SKIP_LINES:
            continue
        if not first_line:
            first_line = line[:40]
        m = VERSION_RE.search(line)
        if m:
            return m.group(0), first_line
    return None, first_line


def parse_version_list(text: str) -> list[str]:
    """Every version-looking entry in a snapshot, in the order it appears.

    The GitHub watches filter with "json:$[*].tag_name", so the snapshot is
    already an ordered newest-first version list -- that order comes from
    upstream's publication order and is preserved verbatim. A watch on a
    ".../releases/latest" endpoint filters with "json:$.tag_name" and yields a
    single bare string, which becomes a one-element list here.
    """
    entries: list[str] = []
    try:
        payload = json.loads(text)
    except (ValueError, TypeError):
        payload = None

    if isinstance(payload, str):
        entries = [payload]
    elif isinstance(payload, list):
        entries = [str(x) for x in payload if isinstance(x, (str, int, float))]
    else:
        for line in text.splitlines():
            line = line.strip().strip('",[]{}')
            if line and line not in SKIP_LINES:
                entries.append(line)

    out = []
    for e in entries:
        e = e.strip()
        # "beta"/"tip" are rolling tags, not versions. Dropping them here keeps
        # them out of the span rather than teaching the comparator about them.
        if not e or e.lower() in NON_VERSION_TAGS or not VERSION_RE.search(e):
            continue
        out.append(e)
    return out


def normalized_version(v: str) -> str:
    """Version identity for matching. Deliberately dumb.

    Strips a leading v/version and lowercases -- nothing else. No zero-padding
    normalization and no trailing-".0" removal: deciding that 1.02 and 1.2 (or
    7.3 and 7.3.0) are the same version is a semantic judgement we don't need
    for identity. _version_key() handles fuzzy numeric comparison where that
    actually is wanted.
    """
    return re.sub(r"^(version\s+|v)", "", (v or "").strip().lower())


def _index_of_normalized(versions: list[str], target: str | None) -> int | None:
    if not target:
        return None
    want = normalized_version(target)
    for i, v in enumerate(versions):
        if normalized_version(v) == want:
            return i
    return None


def version_span(candidates: list[str], installed: str | None) -> dict:
    """Which releases sit between the installed version and the newest one.

    `candidates` is ordered as upstream published them, newest first, and that
    order is NEVER changed here. Publication order and semantic-version order
    are different things: AdGuard Home interleaves stable and beta lines
    ("v0.107.79", "v0.108.0-b.90", "v0.107.78", ...), which is legitimate, and
    _version_key() cannot order two prereleases of one version anyway. Sorting
    such a list would invent a history that never happened.
    """
    if not candidates:
        return {"versions": [], "partial": False, "boundary_approximate": False}

    idx = _index_of_normalized(candidates, installed)
    if idx is not None:
        # Boundary located exactly: everything above it is what we skipped.
        return {
            "versions": candidates[:idx],
            "partial": False,
            "boundary_approximate": False,
        }

    # No exact match (prerelease suffix drift, a version never published to
    # this endpoint, a "latest"-only snapshot). Fall back to numeric membership
    # -- but keep the upstream order of whatever qualifies.
    latest_key, _ = _version_key(candidates[0])
    inst_key, _ = _version_key(installed or "")
    span = [
        v
        for v in candidates
        if inst_key and _version_key(v)[0] and inst_key < _version_key(v)[0] <= latest_key
    ]
    # Partial means boundary exhaustion: we never found the installed version
    # AND every release we can see is newer than it, so the boundary lies
    # outside the window upstream gave us. If some candidates sort older than
    # installed, the boundary was inside the window after all.
    return {
        "versions": span,
        "partial": bool(span) and len(span) == len(candidates),
        "boundary_approximate": True,
    }


def split_title(title: str) -> tuple[str, str | None]:
    """'Name · 1.2.3' -> ('Name', '1.2.3'); 'Name' -> ('Name', None).

    Strips every trailing version segment, so a title that picked up a stale
    duplicate ('Name · 1.2 · 1.2.3') heals back to 'Name' on the next write."""
    name, version = title.strip(), None
    while TITLE_SEP in name:
        head, tail = name.rsplit(TITLE_SEP, 1)
        if not VERSION_RE.fullmatch(tail.strip()):
            break
        if version is None:
            version = tail.strip()
        name = head.strip()
    return name, version


# ─── Installed versions ──────────────────────────────────────────────────


def _app_version(app_name: str) -> str | None:
    path = f"/Applications/{app_name}.app/Contents/Info.plist"
    try:
        with open(path, "rb") as f:
            info = plistlib.load(f)
        v = info.get("CFBundleShortVersionString") or info.get("CFBundleVersion")
        return str(v).strip() if v else None
    except Exception:
        return None


def _run(cmd: list[str]) -> str:
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=REQUEST_TIMEOUT)
        return (r.stdout or "") + (r.stderr or "")
    except (subprocess.TimeoutExpired, OSError):
        return ""


def read_installed(spec, name: str, cfg: dict) -> tuple[str | None, str]:
    """Resolve a watch's installed version. Returns (version, source label)."""
    if spec is None:
        # Zero-config default: a watch named after an app bundle.
        return _app_version(name), f"app:{name}"
    if isinstance(spec, dict):
        kind = spec.get("type", "")
        if kind == "file":
            try:
                text = Path(os.path.expanduser(spec["path"])).read_text()
                m = re.search(spec["regex"], text)
                return (m.group(1) if m else None), f"file:{Path(spec['path']).name}"
            except Exception:
                return None, f"file:{spec.get('path', '?')}"
        return None, f"unknown type {kind!r}"
    spec = str(spec)
    if spec == "macos":
        ver = _run(["sw_vers", "-productVersion"]).strip()
        build = _run(["sw_vers", "-buildVersion"]).strip()
        return (f"{ver} ({build})" if ver else None), "sw_vers"
    if spec.startswith("app:"):
        return _app_version(spec[4:]), spec
    if spec.startswith("cmd:"):
        out = _run(shlex.split(spec[4:]))
        hits = VERSION_RE.findall(out)
        return (hits[-1] if hits else None), spec
    if spec.startswith("compose:"):
        image = spec[8:]
        try:
            for line in Path(cfg["compose_file"]).read_text().splitlines():
                if "image:" in line and image in line and "#" in line:
                    m = VERSION_RE.search(line.split("#", 1)[1])
                    return (m.group(0) if m else None), spec
        except Exception:
            pass
        return None, spec
    return None, spec


def _version_key(v: str):
    """(numeric tuple, is_prerelease) for ordering comparisons."""
    v = v.strip().lower()
    v = re.sub(r"^(version\s+|v)", "", v)
    m = re.match(r"(\d+(?:\.\d+)*)", v)
    nums = tuple(int(x) for x in m.group(1).split(".")) if m else ()
    rest = v[m.end():] if m else v
    prerelease = bool(re.search(r"(alpha|beta|rc|preview|dev)", rest))
    return nums, prerelease


def compare_versions(installed: str | None, latest: str | None, latest_full: str = "") -> str:
    """'behind', 'current', 'ahead', or 'unknown'."""
    if not installed or not latest:
        return "unknown"
    b_i = re.search(r"\(([0-9A-Za-z]+)\)", installed)
    b_l = re.search(r"\(([0-9A-Za-z]+)\)", latest_full or latest)
    if b_i and b_l:  # macOS-style build ids are the reliable comparison
        return "current" if b_i.group(1) == b_l.group(1) else "behind"
    ni, pi = _version_key(installed)
    nl, pl = _version_key(latest)
    if not ni or not nl:
        return "current" if installed.strip().lstrip("v") == latest.strip().lstrip("v") else "unknown"
    # Pad so 7.3 and 7.3.0 compare equal.
    width = max(len(ni), len(nl))
    ni += (0,) * (width - len(ni))
    nl += (0,) * (width - len(nl))
    if ni < nl:
        return "behind"
    if ni > nl:
        return "ahead"
    if pi and not pl:
        return "behind"
    return "current"


# ─── Fetch ───────────────────────────────────────────────────────────────


def fetch_items(client: Client, cfg: dict) -> tuple[list[dict], str | None, list[str]]:
    watches = client.list_watches(cfg["tag"])
    items: list[dict] = []
    warnings: list[str] = []
    tag_uuid: str | None = None
    puts = 0

    for uuid, w in watches.items():
        title = w.get("title") or w.get("page_title") or w.get("url", uuid)
        name, stored_version = split_title(title)
        tags = w.get("tags") or []
        if tag_uuid is None and tags:
            tag_uuid = tags[0]

        snapshot = client.latest_snapshot(uuid)
        version, first_line = parse_version(snapshot) if snapshot else (None, "")
        # Ordered newest-first, straight from upstream; feeds version_span.
        versions = parse_version_list(snapshot) if snapshot else []
        last_changed = int(w.get("last_changed") or 0)
        # When the current version was first observed: the last detected change,
        # or, for a watch that has never changed, its first snapshot.
        since = last_changed or (client.first_seen(uuid) if snapshot else 0)
        installed, source = read_installed(cfg["installed"].get(name), name, cfg)
        status = compare_versions(installed, version, first_line)

        new_title = f"{name}{TITLE_SEP}{version}" if version is not None else None
        if cfg["update_titles"] and new_title is not None and new_title != title.strip():
            if client.set_title(uuid, new_title):
                puts += 1
                debug(f"title updated: {title!r} -> {new_title!r}")
            else:
                warnings.append(f"Could not update title for {name}")

        items.append(
            {
                "uuid": uuid,
                "name": name,
                "version": version,
                "versions": versions,
                "first_line": first_line,
                "last_changed": last_changed,
                "since": since,
                "installed": installed,
                "source": source,
                "status": status,
                "last_checked": int(w.get("last_checked") or 0),
                "last_error": w.get("last_error") or False,
                "viewed": bool(w.get("viewed", True)),
                "link": w.get("link") or w.get("url") or "",
                "notes": notes_url(name, w.get("url") or "", cfg),
            }
        )

    debug(f"{len(items)} watches, {puts} title updates")
    # Apps that are behind first, then everything else, newest change first.
    items.sort(key=lambda i: (i["status"] != "behind", i["since"] == 0, -i["since"], i["name"].lower()))
    return items, tag_uuid, warnings


# ─── Cache ───────────────────────────────────────────────────────────────


def save_cache(items: list[dict], tag_uuid: str | None) -> None:
    try:
        CACHE_FILE.parent.mkdir(parents=True, exist_ok=True)
        CACHE_FILE.write_text(
            json.dumps(
                {"timestamp": time.time(), "tag_uuid": tag_uuid, "items": items}
            )
        )
    except Exception:
        pass


def load_cache() -> dict | None:
    try:
        payload = json.loads(CACHE_FILE.read_text())
        if time.time() - float(payload["timestamp"]) > CACHE_MAX_AGE_HOURS * 3600:
            return None
        return payload
    except Exception:
        return None


# ─── Summaries ───────────────────────────────────────────────────────────
# Two fingerprints decide whether a cached entry is still valid:
#   content_fp  (model, prompt version, repo) invalidates ready/none results --
#               a changed summary_repo must not leave a summary of the wrong
#               project cached forever under an unchanged key.
#   exec_fp     (llm path, model) invalidates errors, so correcting a bad model
#               or path retries at once instead of waiting out the backoff.


def _content_fp(cfg: dict, repo: str) -> str:
    return f"{cfg['summary_model']}|{SUMMARY_PROMPT_VERSION}|{repo}"


def _exec_fp(cfg: dict) -> str:
    return f"{cfg['llm_path']}|{cfg['summary_model']}"


def summary_key(name: str, installed: str | None, latest: str | None) -> str:
    return f"{name}|{installed or '?'}|{latest or '?'}"


def load_summaries(cfg: dict) -> dict:
    try:
        payload = json.loads(summary_file(cfg).read_text())
        if int(payload.get("schema", 0)) != SUMMARY_CACHE_SCHEMA:
            return {"schema": SUMMARY_CACHE_SCHEMA, "entries": {}}
        payload.setdefault("entries", {})
        return payload
    except Exception:
        return {"schema": SUMMARY_CACHE_SCHEMA, "entries": {}}


def save_summaries(cfg: dict, payload: dict) -> None:
    """Atomic replace: render reads this file while the worker may be writing."""
    entries = payload.get("entries") or {}
    if len(entries) > 200:
        keep = sorted(
            entries.items(), key=lambda kv: kv[1].get("updated_at", 0), reverse=True
        )[:200]
        payload["entries"] = dict(keep)
    payload["schema"] = SUMMARY_CACHE_SCHEMA
    path = summary_file(cfg)
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".json.tmp")
        tmp.write_text(json.dumps(payload))
        os.replace(tmp, path)
    except Exception as exc:
        debug(f"summary cache write failed: {exc}")


def summary_repo_for(item: dict, cfg: dict) -> str | None:
    """owner/repo for a watch, or None if it has no GitHub source."""
    override = cfg["summary_repo"].get(item["name"])
    if override:
        return str(override)
    m = re.match(r"https://api\.github\.com/repos/([^/]+/[^/]+)/", item.get("link") or "")
    return m.group(1) if m else None


def needs_work(entry: dict | None, cfg: dict, repo: str, now: float) -> bool:
    if not entry:
        return True
    state = entry.get("state")
    if state in ("ready", "none"):
        return entry.get("content_fp") != _content_fp(cfg, repo)
    if state == "error":
        if entry.get("exec_fp") != _exec_fp(cfg):
            return True  # configuration changed: retry immediately
        return now >= float(entry.get("retry_after", 0))
    return True


def github_releases(repo: str) -> list[dict] | None:
    """[{tag, body}] newest-first as upstream returned them, or None on failure.

    Unauthenticated on purpose. The worst case is one request per behind app
    against a 60/hour limit, and the `gh` token on this machine carries repo
    and workflow scopes -- a write-capable credential has no business reading
    public release notes.
    """
    url = f"{GITHUB_API}/repos/{repo}/releases?per_page=10"
    req = urllib.request.Request(url, headers={
        "User-Agent": GITHUB_UA,
        "Accept": "application/vnd.github+json",
    })
    try:
        with urllib.request.urlopen(req, timeout=REQUEST_TIMEOUT) as resp:
            payload = json.loads(resp.read().decode("utf-8", "replace"))
    except Exception as exc:
        debug(f"github {repo}: {exc}")
        return None
    if not isinstance(payload, list):
        return None
    return [
        {"tag": str(r.get("tag_name") or ""), "body": str(r.get("body") or "")}
        for r in payload
        if isinstance(r, dict)
    ]


def collect_notes(releases: list[dict], span: list[str], cfg: dict) -> dict:
    """Release notes for the span. Returns {text, found, total}.

    Each body is tested against MIN_NOTES_CHARS on its own, before anything is
    joined: projects whose body is just a changelog link run ~56 chars, and two
    of those concatenated would otherwise clear the floor and buy an LLM call
    that summarizes a pair of URLs.
    """
    by_norm = {normalized_version(r["tag"]): r for r in releases}
    kept: list[tuple[str, str]] = []
    for v in span:
        rel = by_norm.get(normalized_version(v))
        if not rel:
            continue
        body = rel["body"].strip()
        if len(body) < MIN_NOTES_CHARS:
            continue
        kept.append((rel["tag"] or v, body))

    if not kept:
        return {"text": "", "found": 0, "total": len(span)}

    # Budget per release rather than truncating one big newest-first blob --
    # that would drop the oldest skipped releases entirely, and those are
    # exactly the ones you haven't seen. Some projects run ~12k chars each.
    per = max(400, (cfg["summary_max_input_chars"] // len(kept)) - 40)
    chunks = [f"## {tag}\n{body[:per]}" for tag, body in kept]
    return {"text": "\n\n".join(chunks), "found": len(kept), "total": len(span)}


def clean_summary(raw: str, cfg: dict) -> str:
    """Enforce the tooltip contract in code; the prompt can only request it."""
    text = (raw or "").strip()
    # Strip markdown emphasis/heading/bullet leaders line by line, then flatten
    # to a single line: esc_tooltip escapes newlines to a literal \n and
    # SwiftBar documents no newline contract for tooltips.
    lines = []
    for line in text.splitlines():
        line = re.sub(r"^\s*(?:[-*+•]|\d+[.)])\s+", "", line).strip()
        line = re.sub(r"^#{1,6}\s*", "", line)
        line = line.replace("**", "").replace("__", "").replace("`", "")
        if line:
            lines.append(line)
    text = " · ".join(lines)
    text = re.sub(r"\s+", " ", text).strip(" ·\t ")

    limit = cfg["summary_max_chars"]
    if len(text) > limit:
        cut = text[: limit - 1]
        if " " in cut:
            cut = cut[: cut.rfind(" ")]
        text = cut.rstrip(" ·,;:") + "…"
    return text


def summarize(item: dict, span: dict, notes: dict, cfg: dict) -> str | None:
    """Run the model. None on any failure -- caller records an error state."""
    covered = ", ".join(span["versions"]) or "unknown"
    coverage = "complete"
    if span["partial"]:
        coverage = "partial (only the releases still listed upstream)"
    elif span["boundary_approximate"]:
        coverage = "approximate (installed version not listed upstream)"
    if notes["found"] < notes["total"]:
        coverage += f"; notes available for {notes['found']} of {notes['total']} releases"

    prompt = (
        f"Software: {item['name']}\n"
        f"Installed: {item.get('installed') or 'unknown'}\n"
        f"Latest: {item.get('version') or 'unknown'}\n"
        f"Releases covered: {covered}\n"
        f"Coverage: {coverage}\n\n"
        f"<release_notes>\n{notes['text']}\n</release_notes>\n"
    )
    cmd = [
        cfg["llm_path"],
        "-m", cfg["summary_model"],
        "-s", SUMMARY_SYSTEM_PROMPT.format(max_chars=cfg["summary_max_chars"]),
        "-n",            # keep these prompts out of llm's own SQLite log
        "--no-stream",
    ]
    # Not _run(): that merges stderr into stdout, discards the return code, and
    # shares the 10s REQUEST_TIMEOUT, which is far too short for a model call.
    try:
        r = subprocess.run(
            cmd, input=prompt, capture_output=True, text=True,
            timeout=cfg["summary_timeout"],
        )
    except (subprocess.TimeoutExpired, OSError) as exc:
        debug(f"llm {item['name']}: {exc}")
        return None
    if r.returncode != 0:
        debug(f"llm {item['name']}: exit {r.returncode}: {(r.stderr or '').strip()[:200]}")
        return None

    text = clean_summary(r.stdout, cfg)
    if not text:
        return None
    if text.lower().startswith("no user-facing changes"):
        return "No user-facing changes"
    if span["partial"]:
        text = f"Partial — available releases only: {text}"
    elif notes["found"] < notes["total"]:
        text = f"Partial notes — {text}"
    return text


def pending_items(items: list[dict], cfg: dict, cache: dict, now: float) -> list[dict]:
    """Behind rows with a GitHub source whose summary needs generating."""
    out = []
    for i in items:
        if i.get("status") != "behind":
            continue
        repo = summary_repo_for(i, cfg)
        if not repo:
            continue
        key = summary_key(i["name"], i.get("installed"), i.get("version"))
        if needs_work((cache.get("entries") or {}).get(key), cfg, repo, now):
            out.append(i)
    return out


def run_summary_worker(cfg: dict, force: bool = False) -> None:
    """Detached pass that fills the summary cache. Prints nothing, ever."""
    if not cfg["summaries"]:
        return
    try:
        SUMMARY_DIR.mkdir(parents=True, exist_ok=True)
        lock = open(SUMMARY_LOCK, "w")
    except OSError as exc:
        debug(f"lock open failed: {exc}")
        return
    try:
        # Advisory and non-blocking: the OS drops it if we die, so there is no
        # stale-lock heuristic to get wrong.
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        debug("another worker holds the lock")
        return

    try:
        cached = load_cache()
        if not cached:
            debug("no item cache; nothing to summarize")
            return
        items = cached.get("items") or []
        now = time.time()
        cache = load_summaries(cfg)

        if not force and now < float(cache.get("next_batch_after", 0)):
            debug("batch gate holds until next cycle")
            return

        todo = pending_items(items, cfg, cache, now)
        if not todo:
            debug("nothing pending")
            # Clear a gate left over from an earlier capped run: with the
            # backlog gone it would otherwise keep blocking spawns, so the next
            # release to appear would wait out a timer set for a queue that no
            # longer exists.
            if cache.pop("next_batch_after", None) is not None:
                save_summaries(cfg, cache)
                debug("batch gate cleared")
            return

        capped = len(todo) > cfg["summary_max_per_run"]
        todo = todo[: cfg["summary_max_per_run"]]
        resolved = 0

        for item in todo:
            repo = summary_repo_for(item, cfg)
            key = summary_key(item["name"], item.get("installed"), item.get("version"))
            entry = (cache.get("entries") or {}).get(key) or {}
            releases = github_releases(repo)

            if releases is None:
                attempts = int(entry.get("attempts", 0)) + 1
                hours = SUMMARY_BACKOFF_HOURS[min(attempts - 1, len(SUMMARY_BACKOFF_HOURS) - 1)]
                cache["entries"][key] = {
                    "state": "error", "reason": "github_unavailable",
                    "attempts": attempts, "retry_after": now + hours * 3600,
                    "exec_fp": _exec_fp(cfg), "updated_at": now,
                }
                continue

            # The snapshot is the cheap source of candidates, but a watch on a
            # "latest" endpoint yields only one version -- fall back to the tags
            # from the fetch we just made rather than issuing a second request.
            usable = [v for v in (item.get("versions") or []) if VERSION_RE.search(v)]
            if len(usable) >= 2:
                candidates = usable
            else:
                candidates = [
                    r["tag"] for r in releases
                    if r["tag"].lower() not in NON_VERSION_TAGS and VERSION_RE.search(r["tag"])
                ]

            span = version_span(candidates, item.get("installed"))
            notes = collect_notes(releases, span["versions"], cfg)

            if notes["found"] == 0:
                cache["entries"][key] = {
                    "state": "none", "reason": "no_substantive_notes",
                    "content_fp": _content_fp(cfg, repo), "updated_at": now,
                }
                resolved += 1
                debug(f"{item['name']}: no substantive notes")
                continue

            text = summarize(item, span, notes, cfg)
            if text is None:
                attempts = int(entry.get("attempts", 0)) + 1
                hours = SUMMARY_BACKOFF_HOURS[min(attempts - 1, len(SUMMARY_BACKOFF_HOURS) - 1)]
                cache["entries"][key] = {
                    "state": "error", "reason": "llm_failed",
                    "attempts": attempts, "retry_after": now + hours * 3600,
                    "exec_fp": _exec_fp(cfg), "updated_at": now,
                }
                continue

            cache["entries"][key] = {
                "state": "ready", "text": text,
                "content_fp": _content_fp(cfg, repo), "updated_at": now,
            }
            resolved += 1
            debug(f"{item['name']}: {text[:80]}")

        # Hitting the cap only bounds one worker. Without this gate the refresh
        # below would spawn the next worker straight away, turning "5 per run"
        # into a 5 -> refresh -> 5 -> refresh cascade.
        if capped:
            cache["next_batch_after"] = now + 2 * 3600
        else:
            # Backlog cleared -- drop any gate left over from an earlier capped
            # run, or it would keep blocking spawns with nothing to wait for.
            cache.pop("next_batch_after", None)
        save_summaries(cfg, cache)

        # Refresh ONLY when something became visible. Refreshing after a pure
        # failure would re-render, see the work still pending, and spawn
        # another worker -- an endless loop on a bad model or llm path.
        if resolved:
            plugin_id = os.path.basename(os.environ.get("SWIFTBAR_PLUGIN_PATH", __file__))
            subprocess.run(
                ["open", "-g",
                 f"swiftbar://refreshplugin?name={urllib.parse.quote(plugin_id)}"],
                capture_output=True, timeout=REQUEST_TIMEOUT,
            )
    except Exception as exc:
        debug(f"worker failed: {exc}")
    finally:
        try:
            fcntl.flock(lock, fcntl.LOCK_UN)
            lock.close()
        except OSError:
            pass


def spawn_summary_worker() -> None:
    try:
        subprocess.Popen(
            [__file__, "summaries"],
            start_new_session=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        debug("summary worker spawned")
    except OSError as exc:
        debug(f"worker spawn failed: {exc}")


