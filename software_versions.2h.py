def maybe_start_worker(items: list[dict], cfg: dict, cache: dict) -> None:
    """Start at most one detached worker, and only when it has work it may do."""
    if not cfg["summaries"]:
        return
    now = time.time()
    if now < float(cache.get("next_batch_after", 0)):
        debug("batch gate holds; not spawning")
        return
    if pending_items(items, cfg, cache, now):
        spawn_summary_worker()


def main() -> None:
    cfg = load_config()

    # Dispatch before get_api_key(): the worker needs no changedetection
    # credentials (everything it reads is in the item cache), and get_api_key
    # can raise a Keychain prompt, which would be invisible in a detached
    # background process.
    if len(sys.argv) > 1 and sys.argv[1] == "summaries":
        run_summary_worker(cfg, force="--force" in sys.argv)
        return

    api_key = get_api_key(cfg)
    client = Client(cfg["base_url"], api_key)
    try:
        items, tag_uuid, warnings = fetch_items(client, cfg)
        if cfg["alert_template"]:
            try:
                warning = sync_alert_template(client, items, cfg)
            except (RuntimeError, OSError, ValueError) as exc:  # never lose the menu over it
                warning = f"Alert template sync failed: {exc}"
            if warning:
                warnings.append(warning)
        save_cache(items, tag_uuid)
        summaries = load_summaries(cfg)
        render(items, tag_uuid, cfg, warnings, summaries=summaries)
        # After render: the menu is already on screen, so a slow spawn cannot
        # delay it, and the worker reads the cache we just wrote.
        maybe_start_worker(items, cfg, summaries)
    except AuthError as exc:
        print(f"⚠️ | {ICON}")
        print("---")
        print(f"changedetection.io rejected the API key: {esc_label(str(exc))} | color={COLOR_ERROR}")
        print(
            f"Keychain item: -s {cfg['keychain_service']} -a {cfg['keychain_account']} | {FONT_MONO} color={COLOR_DIM}"
        )
        print("---")
        print("Refresh | refresh=true")
    except Exception as exc:
        cached = load_cache()
        if cached:
            render(
                cached["items"], cached.get("tag_uuid"), cfg, [],
                cached_at=cached["timestamp"], summaries=load_summaries(cfg),
            )
        else:
            print(f"⚠️ | {ICON}")
            print("---")
            print(f"Error: {esc_label(str(exc))} | color={COLOR_ERROR}")
            print("---")
            print("Refresh | refresh=true")


if __name__ == "__main__":
    main()
